import {readFile,access} from "node:fs/promises";
import assert from "node:assert/strict";
const root=new URL("../",import.meta.url),candidate=new URL("release-candidate/1.1.0/",root);
const current=JSON.parse(await readFile(new URL(".codex-plugin/plugin.json",root),"utf8"));
const next=JSON.parse(await readFile(new URL(".codex-plugin/plugin.json",candidate),"utf8"));
assert.equal(next.version,"1.1.0");
for(const field of ["name","author","mcpServers","skills"])assert.deepEqual(next[field],current[field]);
for(const field of ["displayName","developerName","websiteURL","privacyPolicyURL","termsOfServiceURL","supportURL","composerIcon","composerIconDark","logo","logoDark"])assert.equal(next.interface[field],current.interface[field]);
assert.ok(next.interface.shortDescription.length<=30);
assert.ok(next.interface.defaultPrompt.length<=3&&next.interface.defaultPrompt.every(p=>typeof p==="string"&&p.length<=128&&!p.includes("@")));
assert.equal(next.extensions["com.openai"].onboardingSkill,"./skills/build-with-one-click/SKILL.md");
assert.deepEqual(JSON.parse(await readFile(new URL(".mcp.json",candidate),"utf8")),JSON.parse(await readFile(new URL(".mcp.json",root),"utf8")));
assert.deepEqual(await readFile(new URL("assets/logo.png",candidate)),await readFile(new URL("assets/logo.png",root)));
await access(new URL(next.extensions["com.openai"].onboardingSkill,candidate));
const skill=await readFile(new URL(next.extensions["com.openai"].onboardingSkill,candidate),"utf8");
assert.match(skill,/^---\nname: build-with-one-click\ndescription: [^\n]+\n---/);
assert.match(skill,/72 hours/);assert.match(skill,/no automatic charge/);assert.match(skill,/app-only/);
assert.ok(!next.apps);
console.log("Native release candidate passed; live 1.0.3 package retained.");
